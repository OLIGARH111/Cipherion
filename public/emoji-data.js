export const emojiKeywords = Object.entries(keywordSource).map(([words, list]) => [words.split(' '), list.split(' ')]);
export function searchEmoji(query) {
  const q = query.trim().toLowerCase().replace(/ё/g, 'е');
  if (!q) return [];
  const found = [];
  for (const [words, list] of emojiKeywords) if (words.some(w => w.replace(/ё/g, 'е').startsWith(q) || q.startsWith(w.replace(/ё/g, 'е')))) found.push(...list);
  return [...new Set(found)];
}

// A message made only of 1–3 emoji (or custom emoji) is shown large without a bubble.
const emojiOnly = /^(?:\p{Extended_Pictographic}|\p{Emoji_Modifier}|\p{Regional_Indicator}|‍|️|⃣|[#*0-9]️?⃣|\s|:ce\[[a-zA-Z0-9-]+\])+$/u;
export function jumboSize(text) {
  const value = String(text || '').trim();
  if (!value || value.length > 64 || !emojiOnly.test(value) || /^[\d#*\s]+$/.test(value)) return 0;
  const custom = (value.match(/:ce\[[a-zA-Z0-9-]+\]/g) || []).length;
  const rest = value.replace(/:ce\[[a-zA-Z0-9-]+\]/g, '').replace(/\s/g, '');
  let count = custom;
  if (rest) count += typeof Intl.Segmenter === 'function' ? [...new Intl.Segmenter('ru', {granularity: 'grapheme'}).segment(rest)].length : Array.from(rest).length;
  return count >= 1 && count <= 3 ? count : 0;
}
